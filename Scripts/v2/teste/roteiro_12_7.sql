DROP TABLE IF EXISTS T_RESULTADO;
CREATE TABLE T_RESULTADO (
  ID       INT AUTO_INCREMENT PRIMARY KEY,
  PASSO    VARCHAR(5)   NOT NULL,
  ITEM     VARCHAR(120) NOT NULL,
  OK       TINYINT(1)   NOT NULL,
  OBTIDO   TEXT         NULL
);

DROP PROCEDURE IF EXISTS T_OK;
DROP PROCEDURE IF EXISTS T_ESPERA_ERRO;
DROP PROCEDURE IF EXISTS T_ESPERA_DUPLICADO;
DROP PROCEDURE IF EXISTS T_FINAL;

DELIMITER $$

-- Verificação simples: p_cond verdadeiro = OK
CREATE PROCEDURE T_OK(IN p_passo VARCHAR(5), IN p_item VARCHAR(120), IN p_cond TINYINT, IN p_obtido TEXT)
BEGIN
  INSERT INTO T_RESULTADO (PASSO, ITEM, OK, OBTIDO) VALUES (p_passo, p_item, COALESCE(p_cond, 0), p_obtido);
END$$

-- Executa p_sql e espera que o banco recuse com a mensagem p_msg (SQLSTATE 45000)
CREATE PROCEDURE T_ESPERA_ERRO(IN p_passo VARCHAR(5), IN p_item VARCHAR(120), IN p_sql TEXT, IN p_msg VARCHAR(255))
BEGIN
  DECLARE v_estado CHAR(5) DEFAULT NULL;
  DECLARE v_msg TEXT DEFAULT NULL;
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    GET DIAGNOSTICS CONDITION 1 v_estado = RETURNED_SQLSTATE, v_msg = MESSAGE_TEXT;
  SET @T_SQL = p_sql;
  PREPARE T_ST FROM @T_SQL;
  EXECUTE T_ST;
  DEALLOCATE PREPARE T_ST;
  INSERT INTO T_RESULTADO (PASSO, ITEM, OK, OBTIDO)
  VALUES (p_passo, p_item, COALESCE(v_estado = '45000' AND v_msg = p_msg, 0),
          COALESCE(CONCAT(v_estado, ': ', v_msg), 'NÃO FOI RECUSADO'));
END$$

-- UNIQUE violada (1062): confere o nome da constraint na mensagem do MySQL
CREATE PROCEDURE T_ESPERA_DUPLICADO(IN p_passo VARCHAR(5), IN p_item VARCHAR(120), IN p_sql TEXT, IN p_chave VARCHAR(64))
BEGIN
  DECLARE v_num INT DEFAULT NULL;
  DECLARE v_msg TEXT DEFAULT NULL;
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
    GET DIAGNOSTICS CONDITION 1 v_num = MYSQL_ERRNO, v_msg = MESSAGE_TEXT;
  SET @T_SQL = p_sql;
  PREPARE T_ST FROM @T_SQL;
  EXECUTE T_ST;
  DEALLOCATE PREPARE T_ST;
  INSERT INTO T_RESULTADO (PASSO, ITEM, OK, OBTIDO)
  VALUES (p_passo, p_item, COALESCE(v_num = 1062 AND v_msg LIKE CONCAT('%', p_chave, '%'), 0),
          COALESCE(CONCAT(v_num, ': ', v_msg), 'NÃO FOI RECUSADO'));
END$$

CREATE PROCEDURE T_FINAL()
BEGIN
  DECLARE v_falhas INT;
  SELECT COUNT(*) INTO v_falhas FROM T_RESULTADO WHERE OK = 0;
  IF v_falhas > 0 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ROTEIRO 12 §7: há verificações com FALHA.';
  END IF;
END$$

