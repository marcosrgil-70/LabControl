USE labcontrol_v2;

-- Clientes (VW_CLIENTES do legado, sem UNION PF/PJ)
CREATE OR REPLACE VIEW VW_CLIENTES AS
SELECT E.ID_EMPRESAS, E.ID_ENTIDADES, E.CATEGORIA, E.CPF_CNPJ, E.NOME, E.NOME_FANTASIA,
       E.RG_IE, E.INSC_MUNICIPAL, E.INSC_SUFRAMA, E.DATA_CADASTRO, E.INATIVO,
       (SELECT CONCAT('(', F.DDD, ') ', F.FONE) FROM ENTIDADES_FONES F
         WHERE F.ID_ENTIDADES = E.ID_ENTIDADES AND F.INATIVO = 0
         ORDER BY F.PRINCIPAL DESC, F.ID_ENTIDADES_FONES LIMIT 1) AS FONE_PRINCIPAL,
       (SELECT M.EMAIL FROM ENTIDADES_EMAILS M
         WHERE M.ID_ENTIDADES = E.ID_ENTIDADES AND M.INATIVO = 0
         ORDER BY M.PRINCIPAL DESC, M.ID_ENTIDADES_EMAILS LIMIT 1) AS EMAIL_PRINCIPAL
  FROM ENTIDADES E
 WHERE E.TIPO_CLIENTE = 1;

-- Endereços completos (substitui VW_ENDERECOS e VW_CLIENTES_ENDERECOS)
CREATE OR REPLACE VIEW VW_ENTIDADES_ENDERECOS AS
SELECT EN.ID_EMPRESAS, EN.ID_ENTIDADES, EN.ID_ENTIDADES_ENDERECOS, EN.ID_ENDERECOS_TIPOS,
       T.DESCRICAO AS ENDERECO_TIPO, T.FINALIDADE, TL.ABREVIATURA AS TIPO_LOGRADOURO, EN.LOGRADOURO,
       EN.NUMERO, EN.COMPLEMENTO, EN.BAIRRO, EN.CEP, C.ID_CIDADES, C.NOME AS CIDADE, C.CODIGO_IBGE AS IBGE_CIDADE,
       UF.SIGLA AS UF, UF.NOME AS ESTADO, P.NOME AS PAIS, EN.INATIVO,
       CONCAT_WS(', ', CONCAT_WS(' ', TL.ABREVIATURA, EN.LOGRADOURO), NULLIF(EN.NUMERO, ''), NULLIF(EN.COMPLEMENTO, '')) AS ENDERECO_LINHA1,
       CONCAT_WS(' - ', NULLIF(EN.BAIRRO, ''), CONCAT(C.NOME, '/', UF.SIGLA), NULLIF(EN.CEP, '')) AS ENDERECO_LINHA2
  FROM ENTIDADES_ENDERECOS EN
  JOIN ENDERECOS_TIPOS T ON T.ID_ENDERECOS_TIPOS = EN.ID_ENDERECOS_TIPOS
  LEFT JOIN TIPOS_LOGRADOURO TL ON TL.ID_TIPOS_LOGRADOURO = EN.ID_TIPOS_LOGRADOURO
  JOIN CIDADES C ON C.ID_CIDADES = EN.ID_CIDADES
  JOIN ESTADOS UF ON UF.ID_ESTADOS = C.ID_ESTADOS
  JOIN PAISES P ON P.ID_PAISES = UF.ID_PAISES;

-- Profissionais (VW_FUNCIONARIO do legado — que exigia ENTIDADES_PF e escondia inativos)
CREATE OR REPLACE VIEW VW_PROFISSIONAIS AS
SELECT E.ID_EMPRESAS, E.ID_ENTIDADES, E.NOME, E.NOME_FANTASIA AS SOBRENOME,
       TRIM(CONCAT(E.NOME, ' ', COALESCE(E.NOME_FANTASIA, ''))) AS NOME_COMPLETO,
       F.NR_REGISTRO_PROFISSIONAL, F.UF_REGISTRO, F.ID_TIPOS_REG_PROFISSIONAL, R.DESCRICAO AS TIPO_REGISTRO,
       CONCAT_WS(' ', R.DESCRICAO, CONCAT_WS('-', F.NR_REGISTRO_PROFISSIONAL, F.UF_REGISTRO)) AS REGISTRO_COMPLETO,
       F.ID_CARGOS_FUNCIONARIOS, C.DESCRICAO AS CARGO, F.ASSINA_BOLETIM, F.EXECUTA_ANALISE,
       (F.ASSINATURA IS NOT NULL) AS TEM_ASSINATURA, E.INATIVO,
       UE.ID_USUARIOS, U.LOGIN
  FROM ENTIDADES_FUNCIONARIOS F
  JOIN ENTIDADES E ON E.ID_ENTIDADES = F.ID_ENTIDADES
  LEFT JOIN TIPOS_REG_PROFISSIONAL R ON R.ID_TIPOS_REG_PROFISSIONAL = F.ID_TIPOS_REG_PROFISSIONAL
  LEFT JOIN CARGOS_FUNCIONARIOS C ON C.ID_CARGOS_FUNCIONARIOS = F.ID_CARGOS_FUNCIONARIOS
  LEFT JOIN USUARIOS_EMPRESAS UE ON UE.ID_EMPRESAS = F.ID_EMPRESAS AND UE.ID_ENTIDADES_FUNC = F.ID_ENTIDADES
  LEFT JOIN USUARIOS U ON U.ID_USUARIOS = UE.ID_USUARIOS;

-- Propostas (VW_LAB_PROPOSTAS do legado — que fazia INNER JOIN na cobrança e sumia propostas)
CREATE OR REPLACE VIEW VW_LAB_PROPOSTAS AS
SELECT P.ID_EMPRESAS, P.ID_LAB_PROPOSTAS, P.NR_PROPOSTA, P.COD_PROPOSTA, P.ANO_PROPOSTA, P.REV_PROPOSTA,
       P.ULTIMA_REVISAO, P.MOTIVO_REVISAO, P.DT_SOLICITACAO, P.DT_VALIDADE, P.DT_ENVIO_CLIENTE, P.DT_AUTORIZACAO,
       P.ID_ENTIDADES, CL.NOME AS CLIENTE_NOME, CL.NOME_FANTASIA AS CLIENTE_FANTASIA, CL.CPF_CNPJ AS CLIENTE_CPF_CNPJ,
       P.ID_ENT_CONTATO, CT.NOME_CONTATO, CT.EMAIL AS CONTATO_EMAIL, CT.DEPARTAMENTO AS CONTATO_DEPARTAMENTO,
       P.ID_ENTIDADES_COMERC, COM.NOME AS COMERCIAL_NOME, P.ID_ENTIDADES_FUNC, FU.NOME AS DIGITADOR_NOME,
       P.ID_ENT_COBRANCA, CB.NOME AS COBRANCA_NOME, CB.CPF_CNPJ AS COBRANCA_CPF_CNPJ,
       P.ID_ENT_CONTATO_RESULTADO, CR.NOME_CONTATO AS CONTATO_RESULTADO, CR.EMAIL AS EMAIL_RESULTADO,
       P.ID_ENT_CONTATO_NF, CN.NOME_CONTATO AS CONTATO_NF, CN.EMAIL AS EMAIL_NF,
       P.ID_ENT_END_LAUDO, P.ID_ENT_END_COBRANCA,
       P.ID_LAB_PROPOSTAS_STATUS, S.DESCRICAO AS STATUS, S.COR AS COR_STATUS,
       P.ID_CONDICOES_PAGTOS, CP.DESCRICAO AS CONDICAO_PAGAMENTO, P.ID_MOEDAS, CONCAT(MO.DESCRICAO, ' (', MO.SIGLA, ')') AS MOEDA,
       P.VR_SOMA_VR_ANALIS, P.VR_SOMA_DESC_ANALIS, P.VR_SOMA_VR_TOT_ANALIS, P.PORC_DESCONTO, P.VR_DESCONTO, P.VR_TOTAL_PROPOSTA,
       PV.ID_PEDIDOS_VENDA, PV.NR_PEDIDO, LPAD(PV.NR_PEDIDO, 9, '0') AS NR_PEDIDO_FMT, PV.SITUACAO AS SITUACAO_PEDIDO
  FROM LAB_PROPOSTAS P
  JOIN ENTIDADES CL ON CL.ID_ENTIDADES = P.ID_ENTIDADES
  LEFT JOIN ENTIDADES_EMAILS CT ON CT.ID_ENTIDADES_EMAILS = P.ID_ENT_CONTATO
  LEFT JOIN ENTIDADES COM ON COM.ID_ENTIDADES = P.ID_ENTIDADES_COMERC
  LEFT JOIN ENTIDADES FU ON FU.ID_ENTIDADES = P.ID_ENTIDADES_FUNC
  LEFT JOIN ENTIDADES CB ON CB.ID_ENTIDADES = P.ID_ENT_COBRANCA
  LEFT JOIN ENTIDADES_EMAILS CR ON CR.ID_ENTIDADES_EMAILS = P.ID_ENT_CONTATO_RESULTADO
  LEFT JOIN ENTIDADES_EMAILS CN ON CN.ID_ENTIDADES_EMAILS = P.ID_ENT_CONTATO_NF
  JOIN LAB_PROPOSTAS_STATUS S ON S.ID_LAB_PROPOSTAS_STATUS = P.ID_LAB_PROPOSTAS_STATUS
  LEFT JOIN CONDICOES_PAGTOS CP ON CP.ID_CONDICOES_PAGTOS = P.ID_CONDICOES_PAGTOS
  LEFT JOIN MOEDAS MO ON MO.ID_MOEDAS = P.ID_MOEDAS
  LEFT JOIN PEDIDOS_VENDA PV ON PV.ID_EMPRESAS = P.ID_EMPRESAS AND PV.ANO_PROPOSTA = P.ANO_PROPOSTA
                            AND PV.COD_PROPOSTA = P.COD_PROPOSTA;

-- Itens de análise da proposta (grid de análises / impressão da proposta e do pedido)
CREATE OR REPLACE VIEW VW_LAB_PROPOSTAS_ANALISES AS
SELECT PA.ID_EMPRESAS, PA.ID_LAB_PROPOSTAS, PA.ID_LAB_PROPOSTAS_PRODANALISES, PP.ID_LAB_PROPOSTAS_PRODUTOS, PP.ITEM,
       PP.ID_PRODUTOS, PR.CODIGO AS PRODUTO_CODIGO, PR.DESCRICAO AS PRODUTO_DESCRICAO, PP.QTDE_AMOSTRAS AS QTDE_PRODUTO,
       PA.ID_LAB_PARAMETROS_ANALISES, PAR.DESCRICAO AS PARAMETRO, PAR.DESC_REDUZIDA, PAR.AUDITADO,
       AT.CODIGO AS COD_TIPO_ANALISE, AT.DESCRICAO AS TIPO_ANALISE, M.DESCRICAO AS METODO, I.DESCRICAO AS IDIOMA,
       Z.DESCRICAO AS PRAZO, Z.QTDE_DIAS, PA.TIPO_DOCUMENTO, PA.QTDE_AMOSTRAS, PA.VR_UNITARIO, PA.VR_SUBTOTAL,
       PA.PORC_DESCONTO, PA.VR_DESCONTO, PA.VR_TOTAL, PA.ST_REV_ANTERIOR
  FROM LAB_PROPOSTAS_PRODANALISES PA
  JOIN LAB_PROPOSTAS_PRODUTOS PP ON PP.ID_LAB_PROPOSTAS_PRODUTOS = PA.ID_LAB_PROPOSTAS_PRODUTOS
  JOIN PRODUTOS PR ON PR.ID_PRODUTOS = PP.ID_PRODUTOS
  JOIN LAB_PARAMETROS_ANALISES PAR ON PAR.ID_LAB_PARAMETROS_ANALISES = PA.ID_LAB_PARAMETROS_ANALISES
  JOIN ANALISES_TIPO AT ON AT.ID_ANALISES_TIPO = PAR.ID_ANALISES_TIPO
  JOIN ANALISES_METODOS M ON M.ID_ANALISES_METODOS = PA.ID_ANALISES_METODOS
  JOIN IDIOMAS I ON I.ID_IDIOMAS = PA.ID_IDIOMAS
  JOIN PRAZOS Z ON Z.ID_PRAZOS = PA.ID_PRAZOS;

-- Amostras (VW_LAB_HIST_AMOSTRA do legado, corrigida):
--   * sem INNER JOIN com testes (duplicava linhas: 6.287 linhas para 5.770 amostras)
--   * endereço de correspondência por LEFT JOIN (o legado exigia ID_ENDERECOS_TIPOS = 2)
CREATE OR REPLACE VIEW VW_LAB_AMOSTRAS AS
SELECT A.ID_EMPRESAS, A.ID_LAB_HIST_AMOSTRAS, A.NR_AMOSTRA, A.ANO_AMOSTRA, A.COD_AMOSTRA, A.REVISAO,
       A.ULTIMA_REVISAO, A.MOTIVO_REVISAO, COALESCE(A.ID_AMOSTRA_RAIZ, A.ID_LAB_HIST_AMOSTRAS) AS ID_AMOSTRA_RAIZ,
       A.ID_AMOSTRAS_TIPO, TA.CODIGO AS COD_TIPO_AMOSTRA, TA.DESCRICAO AS TIPO_AMOSTRA,
       A.ID_ANALISES_TIPO, TN.CODIGO AS COD_TIPO_ANALISE, TN.DESCRICAO AS TIPO_ANALISE,
       A.TIPO_DOCUMENTO, A.ID_ENTIDADES, CL.NOME AS CLIENTE_NOME, CL.NOME_FANTASIA AS CLIENTE_FANTASIA,
       CL.CPF_CNPJ AS CLIENTE_CPF_CNPJ, A.NOME_CONTATO,
       A.ID_LAB_PROPOSTAS, P.NR_PROPOSTA, A.ID_LAB_PROPOSTAS_PRODUTOS, PP.ITEM AS ITEM_PROPOSTA,
       A.ID_PEDIDOS_VENDA, LPAD(PV.NR_PEDIDO, 9, '0') AS NR_PEDIDO_FMT,
       A.ID_PRODUTOS, PR.CODIGO AS PRODUTO_CODIGO, PR.DESCRICAO AS PRODUTO_DESCRICAO,
       A.DT_ENTREGA, A.HR_ENTREGA, A.LOCAL_RECEBIMENTO, A.ID_EMBALAGENS_TIPOS, EB.DESCRICAO AS EMBALAGEM,
       A.QTDE_EMBALAGENS_ENTREGUE, A.NR_LOTE,
       FN_DATA_PARCIAL(A.FABRICACAO_DIA, A.FABRICACAO_MES, A.FABRICACAO_ANO) AS FABRICACAO,
       FN_DATA_PARCIAL(A.VALIDADE_DIA, A.VALIDADE_MES, A.VALIDADE_ANO) AS VALIDADE,
       A.NOTA_ROTULO, A.ESPECIE_AMOSTRA, A.ASPECTO_AMOSTRA, A.COR, A.OUTRAS_CARACTERISTICAS,
       A.TEMPERATURA_VERIFICACAO, A.OBSERVACAO_VERIFICACAO, A.NOME_COLETOR, A.DT_HR_COLETA,
       A.ID_AMOSTRAS_STATUS, ST.DESCRICAO AS STATUS_AMOSTRA, ST.COR AS COR_STATUS, ST.PERMITE_RESULTADO,
       A.ID_ENTIDADES_FUNC_RESP, RESP.NOME AS RESPONSAVEL_NOME,
       END_C.ENDERECO_LINHA1, END_C.ENDERECO_LINHA2,
       FN_ACREDITADO(A.ID_LAB_HIST_AMOSTRAS) AS TIPO_ACREDITACAO,
       SD.SALDO_ATUAL, LC.STATUS AS SITUACAO_ARQUIVO,
       EXISTS (SELECT 1 FROM LAB_RESULTADOS_ANALISES R WHERE R.ID_LAB_HIST_AMOSTRAS = A.ID_LAB_HIST_AMOSTRAS) AS TEM_RESULTADO,
       EXISTS (SELECT 1 FROM LAB_BOLETIM_ANALISES B WHERE B.ID_LAB_HIST_AMOSTRAS = A.ID_LAB_HIST_AMOSTRAS
                  AND B.DH_EMISSAO IS NOT NULL) AS TEM_BOLETIM_EMITIDO
  FROM LAB_HIST_AMOSTRAS A
  JOIN AMOSTRAS_TIPO TA ON TA.ID_AMOSTRAS_TIPO = A.ID_AMOSTRAS_TIPO
  JOIN ANALISES_TIPO TN ON TN.ID_ANALISES_TIPO = A.ID_ANALISES_TIPO
  JOIN ENTIDADES CL ON CL.ID_ENTIDADES = A.ID_ENTIDADES
  JOIN LAB_PROPOSTAS P ON P.ID_LAB_PROPOSTAS = A.ID_LAB_PROPOSTAS
  JOIN LAB_PROPOSTAS_PRODUTOS PP ON PP.ID_LAB_PROPOSTAS_PRODUTOS = A.ID_LAB_PROPOSTAS_PRODUTOS
  JOIN PRODUTOS PR ON PR.ID_PRODUTOS = A.ID_PRODUTOS
  JOIN EMBALAGENS_TIPOS EB ON EB.ID_EMBALAGENS_TIPOS = A.ID_EMBALAGENS_TIPOS
  JOIN AMOSTRAS_STATUS ST ON ST.ID_AMOSTRAS_STATUS = A.ID_AMOSTRAS_STATUS
  LEFT JOIN ENTIDADES RESP ON RESP.ID_ENTIDADES = A.ID_ENTIDADES_FUNC_RESP
  LEFT JOIN PEDIDOS_VENDA PV ON PV.ID_PEDIDOS_VENDA = A.ID_PEDIDOS_VENDA
  LEFT JOIN VW_ENTIDADES_ENDERECOS END_C ON END_C.ID_ENTIDADES_ENDERECOS = P.ID_ENT_END_LAUDO
  LEFT JOIN LAB_HIST_AMOSTRAS_SALDO SD ON SD.ID_LAB_HIST_AMOSTRAS = COALESCE(A.ID_AMOSTRA_RAIZ, A.ID_LAB_HIST_AMOSTRAS)
  LEFT JOIN LAB_LOCAL_AMOSTRAS LC ON LC.ID_LAB_HIST_AMOSTRAS = COALESCE(A.ID_AMOSTRA_RAIZ, A.ID_LAB_HIST_AMOSTRAS);

-- Fila de análises: testes da última revisão da amostra sem resultado na última revisão do resultado
CREATE OR REPLACE VIEW VW_LAB_TESTES_PENDENTES AS
SELECT A.ID_EMPRESAS, A.ID_LAB_HIST_AMOSTRAS, A.NR_AMOSTRA, A.DT_ENTREGA, T.ID_LAB_HIST_AMOSTRAS_TESTES,
       T.ID_LAB_PARAMETROS_ANALISES, PA.DESCRICAO AS PARAMETRO, T.DT_PREVISTA,
       DATEDIFF(T.DT_PREVISTA, CURDATE()) AS DIAS_PARA_PRAZO, CL.NOME AS CLIENTE_NOME, PR.DESCRICAO AS PRODUTO_DESCRICAO
  FROM LAB_HIST_AMOSTRAS A
  JOIN AMOSTRAS_STATUS ST ON ST.ID_AMOSTRAS_STATUS = A.ID_AMOSTRAS_STATUS AND ST.PERMITE_RESULTADO = 1
  JOIN LAB_HIST_AMOSTRAS_TESTES T ON T.ID_LAB_HIST_AMOSTRAS = A.ID_LAB_HIST_AMOSTRAS
  JOIN LAB_PARAMETROS_ANALISES PA ON PA.ID_LAB_PARAMETROS_ANALISES = T.ID_LAB_PARAMETROS_ANALISES
  JOIN ENTIDADES CL ON CL.ID_ENTIDADES = A.ID_ENTIDADES
  JOIN PRODUTOS PR ON PR.ID_PRODUTOS = A.ID_PRODUTOS
 WHERE A.ULTIMA_REVISAO = 1
   AND NOT EXISTS (SELECT 1 FROM LAB_RESULTADOS_PARAM RP
                     JOIN LAB_RESULTADOS_ANALISES R ON R.ID_LAB_RESULTADOS_ANALISES = RP.ID_LAB_RESULTADOS_ANALISES
                    WHERE R.ID_LAB_HIST_AMOSTRAS = A.ID_LAB_HIST_AMOSTRAS AND R.ULTIMA_REVISAO = 1
                      AND RP.ID_LAB_HIST_AMOSTRAS_TESTES = T.ID_LAB_HIST_AMOSTRAS_TESTES);

-- Resultados com textos prontos (base da tela de seleção de parâmetros do boletim — qry_Param do legado)
CREATE OR REPLACE VIEW VW_LAB_RESULTADOS AS
SELECT R.ID_EMPRESAS, R.ID_LAB_RESULTADOS_ANALISES, R.ID_LAB_HIST_AMOSTRAS, R.REVISAO, R.ULTIMA_REVISAO,
       RP.ID_LAB_RESULTADOS_PARAM, RP.ID_LAB_HIST_AMOSTRAS_TESTES, PA.ID_LAB_PARAMETROS_ANALISES,
       PA.DESCRICAO AS PARAMETRO, PA.DESC_REDUZIDA, PA.AUDITADO, RP.DT_INICIAL, RP.DT_RESULTADO,
       DATEDIFF(RP.DT_RESULTADO, RP.DT_INICIAL) AS DIAS_ANALISE,
       RP.TIPO_RESULTADO, RP.RESULTADO_FORMATADO, RP.ESPECIF_FORMATADA, U.SIGLA AS UNIDADE,
       CONCAT_WS(' ', FN_FORMATA_DECIMAL(RP.QT_AMOSTRA), UA.SIGLA) AS QT_AMOSTRA_TXT,
       RP.ID_ENTIDADES_FUNC_ANALISE, AN.NOME AS ANALISTA_NOME, RP.VR_SATISFEITO
  FROM LAB_RESULTADOS_ANALISES R
  JOIN LAB_RESULTADOS_PARAM RP ON RP.ID_LAB_RESULTADOS_ANALISES = R.ID_LAB_RESULTADOS_ANALISES
  JOIN LAB_HIST_AMOSTRAS_TESTES T ON T.ID_LAB_HIST_AMOSTRAS_TESTES = RP.ID_LAB_HIST_AMOSTRAS_TESTES
  JOIN LAB_PARAMETROS_ANALISES PA ON PA.ID_LAB_PARAMETROS_ANALISES = T.ID_LAB_PARAMETROS_ANALISES
  LEFT JOIN UNIDADES U ON U.ID_UNIDADES = RP.ID_UNIDADES
  LEFT JOIN UNIDADES UA ON UA.ID_UNIDADES = RP.ID_UNIDADES_AMOSTRA
  LEFT JOIN ENTIDADES AN ON AN.ID_ENTIDADES = RP.ID_ENTIDADES_FUNC_ANALISE;

-- Boletins (consulta da tela de Boletim)
CREATE OR REPLACE VIEW VW_LAB_BOLETINS AS
SELECT B.ID_EMPRESAS, B.ID_LAB_BOLETIM_ANALISES, B.COD_BOLETIM, B.REVISAO, B.ULTIMA_REVISAO, B.MOTIVO_REVISAO,
       B.DT_BOLETIM, B.DH_GERACAO, B.DH_EMISSAO, (B.DH_EMISSAO IS NOT NULL) AS EMITIDO,
       B.ID_BOLETINS_STATUS, S.DESCRICAO AS STATUS_BOLETIM, S.COR AS COR_STATUS,
       B.ID_LAB_HIST_AMOSTRAS, A.NR_AMOSTRA, A.NR_LOTE, A.ID_ENTIDADES, CL.NOME AS CLIENTE_NOME,
       PR.DESCRICAO AS PRODUTO_DESCRICAO, B.ID_LAB_RESULTADOS_ANALISES, R.REVISAO AS REVISAO_RESULTADO,
       B.ID_ENTIDADES_FUNC_RESP, R1.NOME AS RESPONSAVEL1, B.ID_ENTIDADES_FUNC_RESP2, R2.NOME AS RESPONSAVEL2,
       A.DT_ENTREGA
  FROM LAB_BOLETIM_ANALISES B
  JOIN LAB_HIST_AMOSTRAS A ON A.ID_LAB_HIST_AMOSTRAS = B.ID_LAB_HIST_AMOSTRAS
  JOIN ENTIDADES CL ON CL.ID_ENTIDADES = A.ID_ENTIDADES
  JOIN PRODUTOS PR ON PR.ID_PRODUTOS = A.ID_PRODUTOS
  JOIN LAB_RESULTADOS_ANALISES R ON R.ID_LAB_RESULTADOS_ANALISES = B.ID_LAB_RESULTADOS_ANALISES
  LEFT JOIN BOLETINS_STATUS S ON S.ID_BOLETINS_STATUS = B.ID_BOLETINS_STATUS
  LEFT JOIN ENTIDADES R1 ON R1.ID_ENTIDADES = B.ID_ENTIDADES_FUNC_RESP
  LEFT JOIN ENTIDADES R2 ON R2.ID_ENTIDADES = B.ID_ENTIDADES_FUNC_RESP2;

-- Pedido de venda: contratado x recebido por item (casamento por proposta + ITEM, todas as revisões)
CREATE OR REPLACE VIEW VW_PEDIDOS_VENDA_SALDO AS
SELECT PV.ID_EMPRESAS, PV.ID_PEDIDOS_VENDA, PV.NR_PEDIDO, PI.ID_PEDIDOS_VENDA_ITENS, PP.ITEM, PI.ID_PRODUTOS,
       PR.DESCRICAO AS PRODUTO_DESCRICAO, PI.QTDE_CONTRATADA,
       (SELECT COUNT(*) FROM LAB_HIST_AMOSTRAS A
          JOIN LAB_PROPOSTAS PA ON PA.ID_LAB_PROPOSTAS = A.ID_LAB_PROPOSTAS
          JOIN LAB_PROPOSTAS_PRODUTOS PPA ON PPA.ID_LAB_PROPOSTAS_PRODUTOS = A.ID_LAB_PROPOSTAS_PRODUTOS
         WHERE PA.ID_EMPRESAS = PV.ID_EMPRESAS AND PA.ANO_PROPOSTA = PV.ANO_PROPOSTA
           AND PA.COD_PROPOSTA = PV.COD_PROPOSTA AND PPA.ITEM = PP.ITEM AND A.REVISAO = 0) AS QTDE_RECEBIDA
  FROM PEDIDOS_VENDA PV
  JOIN PEDIDOS_VENDA_ITENS PI ON PI.ID_PEDIDOS_VENDA = PV.ID_PEDIDOS_VENDA
  JOIN LAB_PROPOSTAS_PRODUTOS PP ON PP.ID_LAB_PROPOSTAS_PRODUTOS = PI.ID_LAB_PROPOSTAS_PRODUTOS
  JOIN PRODUTOS PR ON PR.ID_PRODUTOS = PI.ID_PRODUTOS;
