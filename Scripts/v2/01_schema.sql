-- =====================================================================
-- LabControl v2 — Schema MySQL 8.0+
-- Origem: Firebird 2.5 (C:\Project\Laboratorio\DBMAIS.FDB)
-- Documentação: docs/banco/11-MODELO-MYSQL.md
--
-- Ordem de execução:
--   01_schema.sql -> 02_funcoes_procedures.sql -> 03_triggers.sql
--   -> 04_views.sql -> 05_seed.sql
--
-- Convenções:
--   * Nomes de tabelas/colunas preservados do Firebird (MAIÚSCULAS_COM_
--     UNDERSCORE) para rastreabilidade; typos corrigidos (ver doc 11).
--   * MULTIEMPRESA: toda tabela de cadastro e movimento possui
--     ID_EMPRESAS. Exceções globais: EMPRESAS, PAISES, ESTADOS, CIDADES,
--     USUARIOS, PERMISSOES, SEQUENCIAS (chave inclui empresa).
--   * Valores monetários DECIMAL(15,2); quantidades DECIMAL(15,4).
--   * Booleanos TINYINT(1) (0/1) — no Firebird eram CHAR(1) 'S'/'N'.
--   * Colunas de auditoria: CRIADO_EM, CRIADO_POR, ALTERADO_EM, ALTERADO_POR
--     (ID_USUARIOS). Preenchidas pela aplicação.
-- =====================================================================

CREATE DATABASE IF NOT EXISTS labcontrol_v2
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_0900_ai_ci;

USE labcontrol_v2;

SET FOREIGN_KEY_CHECKS = 0;

-- =====================================================================
-- 1. NÚCLEO GLOBAL: EMPRESAS, GEOGRAFIA (IBGE), USUÁRIOS E PERMISSÕES
-- =====================================================================

CREATE TABLE PAISES (
  ID_PAISES        INT AUTO_INCREMENT PRIMARY KEY,
  NOME             VARCHAR(80)  NOT NULL,
  SIGLA            VARCHAR(5)   NULL,
  CODIGO_BACEN     VARCHAR(10)  NULL,
  CONSTRAINT UQ_PAISES_NOME UNIQUE (NOME)
) ENGINE=InnoDB;

CREATE TABLE ESTADOS (
  ID_ESTADOS       INT AUTO_INCREMENT PRIMARY KEY,
  ID_PAISES        INT          NOT NULL,
  NOME             VARCHAR(100) NOT NULL,
  SIGLA            CHAR(2)      NOT NULL,
  CODIGO_IBGE      VARCHAR(2)   NULL,
  CONSTRAINT UQ_ESTADOS_SIGLA UNIQUE (ID_PAISES, SIGLA),
  CONSTRAINT FK_ESTADOS_PAISES FOREIGN KEY (ID_PAISES) REFERENCES PAISES (ID_PAISES)
) ENGINE=InnoDB;

CREATE TABLE CIDADES (
  ID_CIDADES       INT AUTO_INCREMENT PRIMARY KEY,
  ID_ESTADOS       INT          NOT NULL,
  NOME             VARCHAR(150) NOT NULL,
  CODIGO_IBGE      VARCHAR(7)   NULL,
  CONSTRAINT UQ_CIDADES_IBGE UNIQUE (CODIGO_IBGE),
  INDEX IX_CIDADES_NOME (ID_ESTADOS, NOME),
  CONSTRAINT FK_CIDADES_ESTADOS FOREIGN KEY (ID_ESTADOS) REFERENCES ESTADOS (ID_ESTADOS)
) ENGINE=InnoDB;

CREATE TABLE EMPRESAS (
  ID_EMPRESAS      INT AUTO_INCREMENT PRIMARY KEY,
  COD_EMPRESA      VARCHAR(3)   NOT NULL,
  RAZAO_SOCIAL     VARCHAR(150) NOT NULL,
  NOME_FANTASIA    VARCHAR(150) NULL,
  CNPJ             VARCHAR(18)  NULL,
  INSC_ESTADUAL    VARCHAR(20)  NULL,
  INSC_MUNICIPAL   VARCHAR(20)  NULL,
  LOGRADOURO       VARCHAR(150) NULL,
  NUMERO           VARCHAR(20)  NULL,
  COMPLEMENTO      VARCHAR(50)  NULL,
  BAIRRO           VARCHAR(80)  NULL,
  CEP              VARCHAR(10)  NULL,
  ID_CIDADES       INT          NULL,
  DDD              VARCHAR(3)   NULL,
  FONE             VARCHAR(20)  NULL,
  EMAIL            VARCHAR(150) NULL,
  SITE             VARCHAR(150) NULL,
  LOGO             MEDIUMBLOB   NULL,
  LOGO_MIME        VARCHAR(50)  NULL,
  CABECALHO_LAUDO  TEXT         NULL,
  RODAPE_LAUDO     TEXT         NULL,
  NR_ACREDITACAO   VARCHAR(50)  NULL COMMENT 'Ex.: CRL INMETRO — exibido no boletim acreditado',
  ATIVA            TINYINT(1)   NOT NULL DEFAULT 1,
  CRIADO_EM        DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ALTERADO_EM      DATETIME     NULL ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT UQ_EMPRESAS_COD UNIQUE (COD_EMPRESA),
  CONSTRAINT UQ_EMPRESAS_CNPJ UNIQUE (CNPJ),
  CONSTRAINT FK_EMPRESAS_CIDADES FOREIGN KEY (ID_CIDADES) REFERENCES CIDADES (ID_CIDADES)
) ENGINE=InnoDB;

-- Numeração de documentos por empresa/tipo/ano (substitui EMPRESAS_PARAMETROS.ULT_*,
-- SYS_TABELAS_ID e os SP_GET_COD_*). ANO = 0 para numeração não anual.
CREATE TABLE SEQUENCIAS_DOCUMENTOS (
  ID_EMPRESAS      INT          NOT NULL,
  TIPO_DOCUMENTO   VARCHAR(30)  NOT NULL COMMENT 'AMOSTRA, PROPOSTA, PEDIDO_VENDA, RELATORIO_ENSAIO, PRODUTO',
  ANO              SMALLINT     NOT NULL DEFAULT 0,
  ULTIMO_NUMERO    INT          NOT NULL DEFAULT 0,
  ALTERADO_EM      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (ID_EMPRESAS, TIPO_DOCUMENTO, ANO),
  CONSTRAINT FK_SEQ_EMPRESAS FOREIGN KEY (ID_EMPRESAS) REFERENCES EMPRESAS (ID_EMPRESAS)
) ENGINE=InnoDB;

CREATE TABLE USUARIOS (
  ID_USUARIOS        INT AUTO_INCREMENT PRIMARY KEY,
  LOGIN              VARCHAR(30)  NOT NULL,
  NOME               VARCHAR(100) NOT NULL,
  EMAIL              VARCHAR(150) NULL,
  SENHA_HASH         VARCHAR(255) NOT NULL COMMENT 'PBKDF2 (ASP.NET Identity PasswordHasher)',
  ADMIN_GLOBAL       TINYINT(1)   NOT NULL DEFAULT 0 COMMENT 'Acesso total a todas as empresas',
  ATIVO              TINYINT(1)   NOT NULL DEFAULT 1,
  TROCAR_SENHA       TINYINT(1)   NOT NULL DEFAULT 1,
  TENTATIVAS_FALHAS  INT          NOT NULL DEFAULT 0,
  BLOQUEADO_ATE      DATETIME     NULL,
  ULTIMO_ACESSO      DATETIME     NULL,
  ID_EMPRESAS_ULTIMA INT          NULL COMMENT 'Última empresa usada (pré-seleção no login)',
  USUCOD_LEGADO      INT          NULL COMMENT 'USUARIO.USUCOD do Firebird',
  CRIADO_EM          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ALTERADO_EM        DATETIME     NULL ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT UQ_USUARIOS_LOGIN UNIQUE (LOGIN)
) ENGINE=InnoDB;

-- Empresas que o usuário acessa e o Profissional (funcionário) que ele representa
-- em cada empresa. Este vínculo substitui USUARIO.ID_ENTIDADES_FUNC do Firebird.
CREATE TABLE USUARIOS_EMPRESAS (
  ID_USUARIOS        INT          NOT NULL,
  ID_EMPRESAS        INT          NOT NULL,
  ID_ENTIDADES_FUNC  INT          NULL COMMENT 'Profissional vinculado ao usuário nesta empresa',
  PADRAO             TINYINT(1)   NOT NULL DEFAULT 0,
  ATIVO              TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (ID_USUARIOS, ID_EMPRESAS),
  CONSTRAINT UQ_USUEMP_FUNC UNIQUE (ID_EMPRESAS, ID_ENTIDADES_FUNC),
  CONSTRAINT FK_USUEMP_USUARIOS FOREIGN KEY (ID_USUARIOS) REFERENCES USUARIOS (ID_USUARIOS),
  CONSTRAINT FK_USUEMP_EMPRESAS FOREIGN KEY (ID_EMPRESAS) REFERENCES EMPRESAS (ID_EMPRESAS)
  -- FK para ENTIDADES_FUNCIONARIOS criada no fim do script
) ENGINE=InnoDB;

-- Catálogo global de permissões (tela + ação). Ex.: AMOSTRAS.INCLUIR
CREATE TABLE PERMISSOES (
  ID_PERMISSOES    INT AUTO_INCREMENT PRIMARY KEY,
  CODIGO           VARCHAR(60)  NOT NULL,
  MODULO           VARCHAR(40)  NOT NULL,
  TELA             VARCHAR(60)  NOT NULL,
  ACAO             VARCHAR(30)  NOT NULL,
  DESCRICAO        VARCHAR(150) NOT NULL,
  ORDEM            INT          NOT NULL DEFAULT 0,
  CONSTRAINT UQ_PERMISSOES_COD UNIQUE (CODIGO)
) ENGINE=InnoDB;

CREATE TABLE PERFIS (
  ID_PERFIS        INT AUTO_INCREMENT PRIMARY KEY,
  ID_EMPRESAS      INT          NOT NULL,
  NOME             VARCHAR(60)  NOT NULL,
  DESCRICAO        VARCHAR(200) NULL,
  ATIVO            TINYINT(1)   NOT NULL DEFAULT 1,
  CONSTRAINT UQ_PERFIS_NOME UNIQUE (ID_EMPRESAS, NOME),
  CONSTRAINT FK_PERFIS_EMPRESAS FOREIGN KEY (ID_EMPRESAS) REFERENCES EMPRESAS (ID_EMPRESAS)
) ENGINE=InnoDB;

CREATE TABLE PERFIS_PERMISSOES (
  ID_PERFIS        INT NOT NULL,
  ID_PERMISSOES    INT NOT NULL,
  PRIMARY KEY (ID_PERFIS, ID_PERMISSOES),
  CONSTRAINT FK_PERFPERM_PERFIS FOREIGN KEY (ID_PERFIS) REFERENCES PERFIS (ID_PERFIS) ON DELETE CASCADE,
  CONSTRAINT FK_PERFPERM_PERMISSOES FOREIGN KEY (ID_PERMISSOES) REFERENCES PERMISSOES (ID_PERMISSOES)
) ENGINE=InnoDB;

CREATE TABLE USUARIOS_PERFIS (
  ID_USUARIOS      INT NOT NULL,
  ID_EMPRESAS      INT NOT NULL,
  ID_PERFIS        INT NOT NULL,
  PRIMARY KEY (ID_USUARIOS, ID_EMPRESAS, ID_PERFIS),
  CONSTRAINT FK_USUPERF_USUEMP FOREIGN KEY (ID_USUARIOS, ID_EMPRESAS) REFERENCES USUARIOS_EMPRESAS (ID_USUARIOS, ID_EMPRESAS) ON DELETE CASCADE,
  CONSTRAINT FK_USUPERF_PERFIS FOREIGN KEY (ID_PERFIS) REFERENCES PERFIS (ID_PERFIS)
) ENGINE=InnoDB;

-- Auditoria genérica gravada pela aplicação (antes/depois em JSON)
CREATE TABLE AUDITORIA (
  ID_AUDITORIA     BIGINT AUTO_INCREMENT PRIMARY KEY,
  ID_EMPRESAS      INT          NULL,
  ID_USUARIOS      INT          NULL,
  TABELA           VARCHAR(60)  NOT NULL,
  ID_REGISTRO      VARCHAR(60)  NOT NULL,
  ACAO             CHAR(1)      NOT NULL COMMENT 'I, A, E, R (revisão), M (emissão)',
  DADOS_ANTES      JSON         NULL,
  DADOS_DEPOIS     JSON         NULL,
  IP               VARCHAR(45)  NULL,
  DT_EVENTO        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX IX_AUDITORIA_REG (TABELA, ID_REGISTRO),
  INDEX IX_AUDITORIA_DATA (ID_EMPRESAS, DT_EVENTO)
) ENGINE=InnoDB;

