-- =====================================================================
-- Empresa usuária: a identidade (razão social, fantasia, CNPJ, inscrições,
-- situação) é mantida em EMPRESAS e espelhada na entidade da empresa, que
-- guarda os endereços, telefones e e-mails (EMPRESAS.ID_ENTIDADES).
-- =====================================================================
CREATE TRIGGER TG_EMPRESAS_AU AFTER UPDATE ON EMPRESAS FOR EACH ROW
BEGIN
  IF NEW.ID_ENTIDADES IS NOT NULL THEN
    UPDATE ENTIDADES
       SET NOME = NEW.RAZAO_SOCIAL, NOME_FANTASIA = NEW.NOME_FANTASIA, CPF_CNPJ = NEW.CNPJ,
           RG_IE = NEW.INSC_ESTADUAL, INSC_MUNICIPAL = NEW.INSC_MUNICIPAL, INATIVO = 1 - NEW.ATIVA
     WHERE ID_ENTIDADES = NEW.ID_ENTIDADES;
  END IF;
END$$

-- =====================================================================
-- Entidades: a empresa usuária não coexiste com outro tipo (legado teEMP)
-- e não deixa de ser empresa usuária enquanto a empresa apontar para ela.
-- =====================================================================
CREATE TRIGGER TG_ENT_BI BEFORE INSERT ON ENTIDADES FOR EACH ROW
BEGIN
  CALL PR_CONFERIR_TIPOS_ENTIDADE(NEW.TIPO_EMPRESA_USUARIA,
       NEW.TIPO_CLIENTE + NEW.TIPO_FORNECEDOR + NEW.TIPO_FUNCIONARIO + NEW.TIPO_VENDEDOR + NEW.TIPO_TRANSPORTADOR);
END$$

CREATE TRIGGER TG_ENT_BU BEFORE UPDATE ON ENTIDADES FOR EACH ROW
BEGIN
  CALL PR_CONFERIR_TIPOS_ENTIDADE(NEW.TIPO_EMPRESA_USUARIA,
       NEW.TIPO_CLIENTE + NEW.TIPO_FORNECEDOR + NEW.TIPO_FUNCIONARIO + NEW.TIPO_VENDEDOR + NEW.TIPO_TRANSPORTADOR);
  IF OLD.TIPO_EMPRESA_USUARIA = 1 AND NEW.TIPO_EMPRESA_USUARIA = 0
     AND EXISTS (SELECT 1 FROM EMPRESAS WHERE ID_ENTIDADES = OLD.ID_ENTIDADES) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Este cadastro é o da própria empresa e não pode deixar de ser empresa usuária.';
  END IF;
END$$

-- =====================================================================
-- Contatos das entidades: filhos herdam ID_EMPRESAS do pai; um endereço
-- ativo por tipo; um telefone e um e-mail principal (inativo não é principal).
-- =====================================================================
CREATE TRIGGER TG_ENTEND_BI BEFORE INSERT ON ENTIDADES_ENDERECOS FOR EACH ROW
BEGIN
  DECLARE v_emp INT;
  SELECT ID_EMPRESAS INTO v_emp FROM ENTIDADES WHERE ID_ENTIDADES = NEW.ID_ENTIDADES;
  CALL PR_CONFERIR_EMPRESA(NEW.ID_EMPRESAS, v_emp);
  SET NEW.ID_EMPRESAS = v_emp;
  IF COALESCE(@LC_MIGRACAO, 0) = 0 THEN
    CALL PR_CONFERIR_ENDERECO(NULL, NEW.ID_ENTIDADES, NEW.ID_ENDERECOS_TIPOS, NEW.INATIVO);
  END IF;
END$$

CREATE TRIGGER TG_ENTEND_BU BEFORE UPDATE ON ENTIDADES_ENDERECOS FOR EACH ROW
BEGIN
  IF NEW.ID_ENTIDADES <> OLD.ID_ENTIDADES OR NEW.ID_EMPRESAS <> OLD.ID_EMPRESAS THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Não é permitido mover o endereço para outro cadastro.';
  END IF;
  IF COALESCE(@LC_MIGRACAO, 0) = 0 THEN
    CALL PR_CONFERIR_ENDERECO(NEW.ID_ENTIDADES_ENDERECOS, NEW.ID_ENTIDADES, NEW.ID_ENDERECOS_TIPOS, NEW.INATIVO);
  END IF;
END$$

