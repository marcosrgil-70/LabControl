-- =====================================================================
-- Propostas
-- =====================================================================
CREATE TRIGGER TG_PROPOSTAS_BI BEFORE INSERT ON LAB_PROPOSTAS FOR EACH ROW
BEGIN
  DECLARE v_num INT;
  IF COALESCE(@LC_MIGRACAO, 0) = 0 THEN
    IF NEW.REV_PROPOSTA <> 0 THEN
      -- revisão: número/ano copiados da origem por SP_GERAR_REVISAO_PROPOSTA (única que inclui revisão)
      IF COALESCE(@LC_REVISAO, 0) = 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Revisões só podem ser geradas pela rotina de revisão.';
      END IF;
    ELSE
      -- número e ano SEMPRE do banco (valor enviado é ignorado); a sequência é por (empresa, ano) e nunca é "zerada"
      SET NEW.ANO_PROPOSTA = YEAR(CURDATE());
      CALL SP_PROXIMO_NUMERO(NEW.ID_EMPRESAS, 'PROPOSTA', NEW.ANO_PROPOSTA, v_num);
      SET NEW.COD_PROPOSTA = v_num;
    END IF;
  END IF;
  IF NEW.DT_SOLICITACAO IS NULL THEN
    SET NEW.DT_SOLICITACAO = CURDATE();
  END IF;
  IF NEW.DT_VALIDADE IS NOT NULL AND NEW.DT_VALIDADE < NEW.DT_SOLICITACAO THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Data de validade anterior à data de solicitação.';
  END IF;
  SET NEW.NR_PROPOSTA = FN_NR_PROPOSTA(NEW.COD_PROPOSTA, NEW.ANO_PROPOSTA, NEW.REV_PROPOSTA);
END$$

CREATE TRIGGER TG_PROPOSTAS_BU BEFORE UPDATE ON LAB_PROPOSTAS FOR EACH ROW
BEGIN
  DECLARE v_envcli INT;
  IF COALESCE(@LC_MIGRACAO, 0) = 0 AND NOT (NEW.ULTIMA_REVISAO <> OLD.ULTIMA_REVISAO) THEN
    IF NEW.ID_EMPRESAS <> OLD.ID_EMPRESAS OR NEW.COD_PROPOSTA <> OLD.COD_PROPOSTA
       OR NEW.ANO_PROPOSTA <> OLD.ANO_PROPOSTA OR NEW.REV_PROPOSTA <> OLD.REV_PROPOSTA THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Número/revisão/empresa da proposta não podem ser alterados.';
    END IF;
    IF OLD.ULTIMA_REVISAO = 0 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Revisão antiga da proposta é somente leitura.';
    END IF;
    -- regra do legado (cds_prinID_STATUS_PROPOSTASChange): status "Enviado ao cliente" grava a data
    SELECT ID_LAB_PROPOSTAS_STATUS_ENVCLI INTO v_envcli FROM EMPRESAS_PARAMETROS WHERE ID_EMPRESAS = NEW.ID_EMPRESAS;
    IF NEW.ID_LAB_PROPOSTAS_STATUS <> OLD.ID_LAB_PROPOSTAS_STATUS AND NEW.ID_LAB_PROPOSTAS_STATUS = v_envcli
       AND NEW.DT_ENVIO_CLIENTE IS NULL THEN
      SET NEW.DT_ENVIO_CLIENTE = CURDATE();
    END IF;
    IF NEW.DT_VALIDADE IS NOT NULL AND NEW.DT_VALIDADE < NEW.DT_SOLICITACAO THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Data de validade anterior à data de solicitação.';
    END IF;
  END IF;
  SET NEW.NR_PROPOSTA = FN_NR_PROPOSTA(NEW.COD_PROPOSTA, NEW.ANO_PROPOSTA, NEW.REV_PROPOSTA);
END$$

CREATE TRIGGER TG_PROPPROD_BI BEFORE INSERT ON LAB_PROPOSTAS_PRODUTOS FOR EACH ROW
BEGIN
  DECLARE v_emp, v_ultima INT;
  -- FOR UPDATE: duas inclusões simultâneas na MESMA proposta esperam uma pela outra (ITEM = MAX + 1 sem repetir)
  SELECT ID_EMPRESAS, ULTIMA_REVISAO INTO v_emp, v_ultima FROM LAB_PROPOSTAS WHERE ID_LAB_PROPOSTAS = NEW.ID_LAB_PROPOSTAS FOR UPDATE;
  CALL PR_CONFERIR_EMPRESA(NEW.ID_EMPRESAS, v_emp);
  SET NEW.ID_EMPRESAS = v_emp;
  IF COALESCE(@LC_MIGRACAO, 0) = 0 THEN
    IF v_ultima = 0 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Revisão antiga da proposta é somente leitura.';
    END IF;
    IF COALESCE(NEW.ITEM, 0) = 0 THEN
      SET NEW.ITEM = (SELECT COALESCE(MAX(ITEM), 0) + 1 FROM LAB_PROPOSTAS_PRODUTOS WHERE ID_LAB_PROPOSTAS = NEW.ID_LAB_PROPOSTAS);
    END IF;
  END IF;
END$$

CREATE TRIGGER TG_PROPPROD_BU BEFORE UPDATE ON LAB_PROPOSTAS_PRODUTOS FOR EACH ROW
